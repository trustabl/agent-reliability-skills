import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";

import { forgeTool, SKILL_DESTINATION, summary } from "./tool.js";

const SKILL = "# Trustabl Pre-Coding Reliability Constraints\n\n<!-- generated: 2026-10-26 | rules: abc | schema: 29 | sdks: claude_sdk | template: 3 -->\n";
const repo = () => fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "forge-tool-test-")));

// Dependencies that record what the handler asked for.
function deps({ result = { code: 0, stdout: SKILL, stderr: "", timedOut: false }, roots = null, binError } = {}) {
  const d = {
    runs: [],
    binCalls: 0,
    ensureBin: async () => {
      d.binCalls++;
      if (binError) throw new Error(binError);
      return "/cache/trustabl";
    },
    run: async (bin, args) => {
      d.runs.push({ bin, args });
      if (result instanceof Error) throw result;
      return result;
    },
    getRoots: async () => roots,
  };
  return d;
}
const texts = (r) => r.content.map((c) => c.text);

test("returns a summary and the SKILL.md, and writes nothing without output_path", async () => {
  const t = repo();
  const d = deps();
  const r = await forgeTool({ path: t }, d);
  assert.equal(r.isError, false);
  assert.equal(texts(r)[1], SKILL);
  assert.match(texts(r)[0], /SDKs: claude_sdk/);
  assert.match(texts(r)[0], /Not written/);
  assert.deepEqual(fs.readdirSync(t), []);
  assert.deepEqual(d.runs, [{ bin: "/cache/trustabl", args: ["forge", t] }]);
});

test("passes policy and lang through to the CLI", async () => {
  const t = repo();
  const d = deps();
  await forgeTool({ path: t, policy: ["openai_sdk"], lang: ["go"] }, d);
  assert.deepEqual(d.runs[0].args, ["forge", t, "--policy", "openai_sdk", "--lang", "go"]);
});

test("writes the skill when output_path is given", async () => {
  const t = repo();
  const r = await forgeTool({ path: t, output_path: SKILL_DESTINATION }, deps());
  const dest = path.join(t, ".claude", "skills", "trustabl-pre-coding", "SKILL.md");
  assert.equal(fs.readFileSync(dest, "utf8"), SKILL);
  assert.match(texts(r)[0], new RegExp(`Written to: ${dest.replace(/[\\^$.*+?()[\]{}|]/g, "\\$&")}`));
});

test("no SDK detected tells the agent to pass policy, not to run the CLI", async () => {
  const stderr =
    'trustabl forge: no SDKs detected in "/r" and no --policy specified\n' +
    "  run 'trustabl forge --policy <category>' to specify one explicitly\n" +
    "  accepted categories: [claude_sdk mcp]\n";
  const r = await forgeTool({ path: repo() }, deps({ result: { code: 1, stdout: "", stderr, timedOut: false } }));
  assert.equal(r.isError, true);
  const text = texts(r)[0];
  assert.match(text, /^Forge found no supported agent SDK/);
  assert.match(text, /call trustabl_forge again with the policy input/);
  assert.match(text, /no SDKs detected in "\/r"/);
  assert.match(text, /accepted categories: \[claude_sdk mcp\]/);
  assert.doesNotMatch(text, /run 'trustabl forge/);
});

test("other exit-1 errors pass through unchanged", async () => {
  const stderr = "trustabl forge: detect SDKs: stat /r: no such file or directory\n";
  const r = await forgeTool({ path: repo() }, deps({ result: { code: 1, stdout: "", stderr, timedOut: false } }));
  assert.equal(texts(r)[0], `trustabl forge exited with code 1:\n${stderr.trim()}`);
});

test("a refused write is an error and leaves the file alone", async () => {
  const t = repo();
  fs.writeFileSync(path.join(t, "SKILL.md"), "mine\n");
  const r = await forgeTool({ path: t, output_path: "SKILL.md" }, deps());
  assert.equal(r.isError, true);
  assert.match(texts(r)[0], /not generated by Forge/);
  assert.equal(fs.readFileSync(path.join(t, "SKILL.md"), "utf8"), "mine\n");
});

test("a CLI failure returns its stderr and exit code", async () => {
  const stderr = 'trustabl forge: unknown policy category "nope"; accepted values: [claude_sdk mcp]\n';
  const r = await forgeTool({ path: repo(), policy: ["nope"] }, deps({ result: { code: 1, stdout: "", stderr, timedOut: false } }));
  assert.equal(r.isError, true);
  assert.equal(texts(r)[0], `trustabl forge exited with code 1:\n${stderr.trim()}`);
});

test("an install failure is reported, not thrown", async () => {
  const r = await forgeTool({ path: repo() }, deps({ binError: "Checksum mismatch for x" }));
  assert.equal(r.isError, true);
  assert.match(texts(r)[0], /Could not install the trustabl binary: Checksum mismatch for x/);
});

test("no path and no roots asks for path before installing anything", async () => {
  const d = deps();
  const r = await forgeTool({}, d);
  assert.equal(r.isError, true);
  assert.match(texts(r)[0], /^Pass `path`/);
  assert.equal(d.binCalls, 0);
});

test("a stderr note from a successful run is included in the summary", async () => {
  const note = "trustabl forge: no supported language detected (python, typescript, go); the Runtime Tracing section is omitted — pass --lang to add one";
  const r = await forgeTool({ path: repo() }, deps({ result: { code: 0, stdout: SKILL, stderr: `${note}\n`, timedOut: false } }));
  assert.match(texts(r)[0], new RegExp(`Note from trustabl: ${note.replace(/[\\^$.*+?()[\]{}|]/g, "\\$&")}`));
});

test("an unexpected exception is reported as a bug, not a crash", async () => {
  const r = await forgeTool({ path: repo() }, deps({ result: new TypeError("boom") }));
  assert.equal(r.isError, true);
  assert.match(texts(r)[0], /Unexpected error in agent-reliability-skills.*boom/s);
});

test("summary says when the output carries no stamp", () => {
  assert.match(summary({ target: "/r", skill: "# no stamp", written: null, note: "" }), /SDKs: unavailable/);
});
