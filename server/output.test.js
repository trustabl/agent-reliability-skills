import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";

import { ToolError } from "./errors.js";
import { resolveOutputPath, writeSkill } from "./output.js";

const STAMPED = "# Skill\n<!-- generated: 2026-10-26 | rules: abc | schema: 29 | sdks: claude_sdk | template: 3 -->\n";
const repo = () => fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "forge-out-test-")));

test("resolveOutputPath resolves a relative path inside the target", () => {
  const t = repo();
  assert.equal(resolveOutputPath(t, ".claude/skills/x/SKILL.md"), path.join(t, ".claude", "skills", "x", "SKILL.md"));
  assert.equal(resolveOutputPath(t, "..notparent/SKILL.md"), path.join(t, "..notparent", "SKILL.md"));
});

test("resolveOutputPath rejects paths outside the target and the target itself", () => {
  const t = repo();
  for (const p of ["../SKILL.md", path.join(os.tmpdir(), "elsewhere.md"), ".", ""]) {
    assert.throws(() => resolveOutputPath(t, p), ToolError, p);
  }
});

test("writeSkill creates parent folders and writes the content", () => {
  const t = repo();
  const dest = writeSkill(t, ".claude/skills/trustabl-pre-coding/SKILL.md", STAMPED);
  assert.equal(fs.readFileSync(dest, "utf8"), STAMPED);
});

test("writeSkill replaces a file Forge generated earlier", () => {
  const t = repo();
  fs.writeFileSync(path.join(t, "SKILL.md"), STAMPED.replace("abc", "old"));
  writeSkill(t, "SKILL.md", STAMPED);
  assert.equal(fs.readFileSync(path.join(t, "SKILL.md"), "utf8"), STAMPED);
});

test("writeSkill never overwrites a hand-written file", () => {
  const t = repo();
  fs.writeFileSync(path.join(t, "SKILL.md"), "my own notes\n");
  assert.throws(() => writeSkill(t, "SKILL.md", STAMPED), /not generated by Forge/);
  assert.equal(fs.readFileSync(path.join(t, "SKILL.md"), "utf8"), "my own notes\n");
});

test("writeSkill refuses a directory", () => {
  const t = repo();
  fs.mkdirSync(path.join(t, "SKILL.md"));
  assert.throws(() => writeSkill(t, "SKILL.md", STAMPED), /is a directory/);
});

test("writeSkill refuses to follow a symlinked folder out of the target", { skip: process.platform === "win32" }, () => {
  const t = repo();
  const outside = repo();
  fs.symlinkSync(outside, path.join(t, "link"));
  assert.throws(() => writeSkill(t, "link/sub/SKILL.md", STAMPED), /symbolic link/);
  assert.equal(fs.existsSync(path.join(outside, "sub")), false);
});

test("writeSkill refuses to write through a symlinked file", { skip: process.platform === "win32" }, () => {
  const t = repo();
  const outside = path.join(repo(), "target.md");
  fs.writeFileSync(outside, STAMPED);
  fs.symlinkSync(outside, path.join(t, "SKILL.md"));
  assert.throws(() => writeSkill(t, "SKILL.md", STAMPED), /symbolic link/);
});
