// The tool's opt-in write. Forge writes only inside the repository it
// generated the skill for, and only replaces a file Forge generated earlier,
// so regenerating a stale skill works but a hand-written file is never lost.
import fs from "node:fs";
import path from "node:path";

import { ToolError } from "./errors.js";
import { parseStamp } from "./stamp.js";

// True when child is strictly inside parent. "..foo" is a name, not a parent hop.
function isInside(parent, child) {
  const rel = path.relative(parent, child);
  return rel !== "" && rel !== ".." && !rel.startsWith(`..${path.sep}`) && !path.isAbsolute(rel);
}

const isInsideOrSame = (parent, child) => path.relative(parent, child) === "" || isInside(parent, child);

// The closest folder on the way up from dir that already exists.
function nearestExisting(dir) {
  let d = dir;
  while (!fs.existsSync(d)) d = path.dirname(d);
  return d;
}

export function resolveOutputPath(targetDir, outputPath) {
  const resolved = path.resolve(targetDir, outputPath);
  if (!isInside(targetDir, resolved)) {
    throw new ToolError(
      `output_path "${outputPath}" resolves to ${resolved}, which is not a file inside the target directory ` +
        `${targetDir}. Forge only writes inside the repository it generated the skill for.`,
    );
  }
  return resolved;
}

export function writeSkill(targetDir, outputPath, content) {
  const dest = resolveOutputPath(targetDir, outputPath);
  const realTarget = fs.realpathSync(targetDir);

  // A symlinked folder inside the target could still lead outside it. Check
  // before creating anything, so a refused write leaves no folders behind.
  if (!isInsideOrSame(realTarget, fs.realpathSync(nearestExisting(path.dirname(dest))))) {
    throw new ToolError(`output_path "${outputPath}" leads outside ${targetDir} through a symbolic link.`);
  }

  // lstat, not exists: a dangling symlink "does not exist" but must still be refused.
  const st = fs.lstatSync(dest, { throwIfNoEntry: false });
  if (st) {
    if (st.isSymbolicLink()) throw new ToolError(`${dest} is a symbolic link; Forge does not write through it.`);
    if (st.isDirectory()) {
      throw new ToolError(`output_path ${dest} is a directory. Name a file, such as .claude/skills/trustabl-pre-coding/SKILL.md.`);
    }
    if (!parseStamp(fs.readFileSync(dest, "utf8"))) {
      throw new ToolError(
        `${dest} already exists and was not generated by Forge (it has no Forge stamp), so it was not ` +
          "overwritten. Choose another output_path, or remove the file first.",
      );
    }
  }

  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, content);
  return dest;
}
